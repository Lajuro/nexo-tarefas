#!/usr/bin/env bash
if grep -q $'\r' "$0" 2>/dev/null; then tr -d '\r' <"$0" >"$0.lf" && NEXO_LF_COPY="$0.lf" exec bash "$0.lf" "$@"; fi #
# =============================================================================
#  nexo-offline.sh  (gerado por scripts/gerar-scripts-de-copia.sh, não edite)
#
#  Instalador SEM rede do repositório Lajuro/nexo-tarefas: o projeto inteiro
#  está aqui dentro (tar.gz em base64). Use quando nem o baixar-nexo.sh
#  consegue acessar o GitHub. Basta copiar este arquivo e rodar.
#
#  Origem: commit ef5cc41 de 2026-11-13 · 55 arquivos · 83 KB compactado
#
#  Uso (no Windows, rode no Git Bash):
#    bash nexo-offline.sh                 # cria a pasta ./nexo-tarefas
#    bash nexo-offline.sh minha-pasta     # escolhe a pasta de destino
#    bash nexo-offline.sh --forcar        # aceita pasta que já tem arquivos
# =============================================================================
set -euo pipefail

SHA256="6dc24fd8ddb06eb16b3aa273845907766f1a902cc3ffdc10c9cf48d143a98ec2"
COMMIT="ef5cc41"
DEST="nexo-tarefas"
FORCE=0
for arg in "$@"; do
  case "$arg" in
    --forcar | --force | -f) FORCE=1 ;;
    -h | --ajuda | --help) sed -n '4,/^# =====/p' "${NEXO_LF_COPY:-$0}" | sed 's/^# \{0,1\}//' | grep -v '^=====' ; exit 0 ;;
    -*) echo "Opção desconhecida: $arg" >&2; exit 1 ;;
    *) DEST="$arg" ;;
  esac
done

die() { echo "✗ $*" >&2; exit 1; }

main() {
  if [ -e "$DEST" ] && [ ! -d "$DEST" ]; then die "\"$DEST\" já existe e não é uma pasta."; fi
  if [ -d "$DEST" ] && [ -n "$(ls -A "$DEST" 2>/dev/null)" ] && [ "$FORCE" = 0 ]; then
    die "A pasta \"$DEST\" já tem arquivos. Escolha outra pasta ou use --forcar."
  fi
  command -v tar >/dev/null 2>&1 || die "Preciso do tar instalado."

  WORK="$(mktemp -d 2>/dev/null || mktemp -d -t nexo)"
  trap 'rm -rf "$WORK"; [ -n "${NEXO_LF_COPY:-}" ] && rm -f "$NEXO_LF_COPY"; true' EXIT
  local work="$WORK"

  echo "› Extraindo o Nexo (commit $COMMIT)…"
  payload | tr -d '\r\n ' >"$work/p.b64"
  if ! base64 -d <"$work/p.b64" >"$work/p.tgz" 2>/dev/null; then
    if ! base64 -D <"$work/p.b64" >"$work/p.tgz" 2>/dev/null; then
      openssl base64 -d -A <"$work/p.b64" >"$work/p.tgz" || die "Não consegui decodificar (falta base64/openssl)."
    fi
  fi

  local actual=""
  if command -v sha256sum >/dev/null 2>&1; then
    actual="$(sha256sum "$work/p.tgz" | cut -d' ' -f1)"
  elif command -v shasum >/dev/null 2>&1; then
    actual="$(shasum -a 256 "$work/p.tgz" | cut -d' ' -f1)"
  fi
  if [ -n "$actual" ] && [ "$actual" != "$SHA256" ]; then
    die "O conteúdo não confere (o arquivo foi alterado ou cortado ao copiar). Copie de novo o script inteiro."
  fi
  [ -n "$actual" ] && echo "✓ Integridade conferida (SHA-256)"

  mkdir -p "$DEST"
  tar -xzf "$work/p.tgz" -C "$DEST"
  # o próprio instalador também faz parte do repositório
  local self="${NEXO_LF_COPY:-$0}"
  if [ -f "$self" ] && [ -d "$DEST/scripts" ]; then cp "$self" "$DEST/scripts/nexo-offline.sh"; fi
  chmod +x "$DEST"/scripts/*.sh 2>/dev/null || true
  echo "✓ Projeto extraído em $DEST ($(tar -tzf "$work/p.tgz" | grep -vc '/$') arquivos)"
  echo
  echo "Próximos passos"
  echo "  cd \"$DEST\""
  echo "  npm install"
  echo "  npm run build"
  echo "  npm start          # abre em http://127.0.0.1:3210 (ou use Iniciar Nexo.cmd)"
}

